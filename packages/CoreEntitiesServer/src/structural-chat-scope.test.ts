import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, it } from 'node:test';
import ts from 'typescript';
import type { IMetadataProvider, UserInfo } from '@memberjunction/core';
import {
    hasStructuralChatScopeAccess,
    type RawStructuralChatScopeRow,
} from '@mj-biz-apps/collaboration-core';
import {
    buildStructuralChatScopeQuery,
    COLLABORATION_CHAT_SCOPE_FUNCTION_NAME,
    detectStructuralChatScopeDialect,
    resolveStructuralChatScope,
    type StructuralChatScopeExecutableProvider,
    type StructuralChatScopeExecuteOptions,
    type StructuralChatScopeSqlParam,
} from '../dist/structural-chat-scope.js';

const CHAT_ID = '44444444-4444-4444-8444-444444444444';
const USER_ID = '88888888-8888-4888-8888-888888888888';
const SPACE_A = '11111111-1111-4111-8111-111111111111';
const SPACE_B = '22222222-2222-4222-8222-222222222222';

function makeMockProvider(
    dialect: 'mssql' | 'postgresql',
    rows: RawStructuralChatScopeRow[],
    capturedCalls: Array<{
        sql: string;
        params: StructuralChatScopeSqlParam[] | undefined;
        options: StructuralChatScopeExecuteOptions | undefined;
    }>,
): IMetadataProvider & StructuralChatScopeExecutableProvider {
    const provider: Partial<IMetadataProvider> & StructuralChatScopeExecutableProvider = {
        PlatformKey: dialect,
        Entities: [],
        async ExecuteSQL(
            query: string,
            parameters?: StructuralChatScopeSqlParam[],
            options?: StructuralChatScopeExecuteOptions,
            _contextUser?: UserInfo,
        ): Promise<RawStructuralChatScopeRow[]> {
            capturedCalls.push({ sql: query, params: parameters, options });
            return rows;
        },
    };
    return provider as IMetadataProvider & StructuralChatScopeExecutableProvider;
}

describe('CS-1 dual-dialect structural chat scope migrations & TypeScript wrappers', () => {
    it('verifies 4-part migration structure, >=50 blank lines, inline TVF / LANGUAGE sql STABLE, and zero roster enumeration', () => {
        const repoRoot = resolve(import.meta.dirname, '..', '..', '..');
        const tsqlPath = resolve(repoRoot, 'migrations/V202611230415__v0.2.x__Structural_Chat_Scope.sql');
        const pgPath = resolve(repoRoot, 'migrations-pg/V202611230415__v0.2.x__Structural_Chat_Scope.pg.sql');
        const tsql = readFileSync(tsqlPath, 'utf8');
        const pgsql = readFileSync(pgPath, 'utf8');

        const codegenBanner = '-- GENERATED BY MemberJunction CodeGen';
        assert.ok(tsql.includes(codegenBanner), 'T-SQL migration must include CodeGen banner');
        assert.ok(pgsql.includes(codegenBanner), 'PG migration must include CodeGen banner');

        const tsqlBefore = tsql.slice(0, tsql.indexOf(codegenBanner));
        const pgBefore = pgsql.slice(0, pgsql.indexOf(codegenBanner));
        assert.ok(tsqlBefore.includes('\n'.repeat(50)), 'T-SQL migration must contain >=50 blank lines before CodeGen section');
        assert.ok(pgBefore.includes('\n'.repeat(50)), 'PG migration must contain >=50 blank lines before CodeGen section');

        // 4-part migration section headers
        for (const section of ['-- 1.', '-- 2.', '-- 3.', '-- 4.']) {
            assert.ok(tsql.includes(section), `T-SQL migration missing section ${section}`);
            assert.ok(pgsql.includes(section), `PG migration missing section ${section}`);
        }

        // Inline TVF in SQL Server (no multi-statement TVF, no OPTION (MAXRECURSION))
        assert.match(tsql, /CREATE OR ALTER FUNCTION \[\$\{flyway:defaultSchema\}\]\.\[fnCollaborationChatScope\]/);
        assert.match(tsql, /RETURNS TABLE\s+AS\s+RETURN\s*\(/);
        assert.equal(/RETURNS\s+@\w+\s+TABLE/i.test(tsql), false, 'T-SQL function must NOT be a multi-statement TVF');
        assert.equal(/OPTION\s*\(\s*MAXRECURSION/i.test(tsql), false, 'Inline T-SQL TVF must NOT contain OPTION (MAXRECURSION)');

        // Set-returning SQL function in PostgreSQL
        assert.match(pgsql, /CREATE OR REPLACE FUNCTION __mj_bizappscollaboration\."fnCollaborationChatScope"\(/);
        assert.match(pgsql, /RETURNS TABLE\s*\(\s*"SpaceID" UUID,\s*"Band" VARCHAR\(20\)\s*\)/);
        assert.match(pgsql, /\$\$ LANGUAGE sql STABLE;/);
        assert.equal(/LANGUAGE plpgsql/i.test(pgsql), false, 'PG function must use LANGUAGE sql STABLE for inline evaluation');

        // Shared CTE structure and (SpaceID, Band) output parity
        for (const cteName of [
            'UserDirectSeats',
            'UserReachable',
            'UserEffectiveAccess',
            'AnchorScope',
            'AncestorCheck',
            'Subtree',
        ]) {
            assert.ok(tsql.includes(cteName), `T-SQL migration missing CTE ${cteName}`);
            assert.ok(pgsql.includes(cteName), `PG migration missing CTE ${cteName}`);
        }

        assert.match(tsql, /SELECT DISTINCT[\s\S]*sub\.\[SpaceID\] AS \[SpaceID\],[\s\S]*bands\.\[Band\] AS \[Band\]/);
        assert.match(pgsql, /SELECT DISTINCT[\s\S]*sub\."SpaceID" AS "SpaceID",[\s\S]*bands\."Band"::VARCHAR\(20\) AS "Band"/);

        // Role permissions and function documentation parity
        for (const role of ['cdp_UI', 'cdp_Developer', 'cdp_Integration']) {
            assert.ok(tsql.includes(`[${role}]`), `T-SQL missing GRANT for ${role}`);
            assert.ok(pgsql.includes(`"${role}"`), `PG missing GRANT for ${role}`);
        }
        assert.ok(tsql.includes("sp_addextendedproperty") && tsql.includes("MS_Description"));
        assert.ok(pgsql.includes('COMMENT ON FUNCTION __mj_bizappscollaboration."fnCollaborationChatScope"'));

        // Absence of roster-enumeration joins / multi-statement access helpers
        for (const forbidden of [
            'STRING_SPLIT',
            'fnCollaborationAccess',
            'fnCollaborationCommonAccess',
            'fnCollaborationAncestorMembers',
            'COUNT(DISTINCT',
        ]) {
            assert.equal(tsql.includes(forbidden), false, `T-SQL must not enumerate rosters via ${forbidden}`);
            assert.equal(pgsql.includes(forbidden), false, `PG must not enumerate rosters via ${forbidden}`);
        }

        // Verify SpaceMember is only referenced once, strictly filtered by UserID = @UserID / p_user_id
        const tsqlSpaceMemberMatches = tsql.match(/SpaceMember/g) ?? [];
        const pgSpaceMemberMatches = pgsql.match(/SpaceMember/g) ?? [];
        assert.equal(tsqlSpaceMemberMatches.length, 1, 'T-SQL must touch SpaceMember strictly in UserDirectSeats');
        assert.equal(pgSpaceMemberMatches.length, 1, 'PG must touch SpaceMember strictly in UserDirectSeats');
        assert.ok(tsql.includes('m.[UserID] = @UserID'), 'T-SQL SpaceMember lookup must be keyed on @UserID');
        assert.ok(pgsql.includes('m."UserID" = p_user_id'), 'PG SpaceMember lookup must be keyed on p_user_id');
    });

    it('detects dialects and builds parameterized dual-dialect queries fail-closed', () => {
        assert.equal(detectStructuralChatScopeDialect({ PlatformKey: 'postgresql' }), 'postgresql');
        assert.equal(detectStructuralChatScopeDialect({ PlatformKey: 'mssql' }), 'mssql');
        assert.equal(detectStructuralChatScopeDialect({}), 'mssql');
        assert.equal(detectStructuralChatScopeDialect({ PlatformKey: 'mssql' }, 'postgresql'), 'postgresql');

        const mssqlSpec = buildStructuralChatScopeQuery('mssql', CHAT_ID, USER_ID);
        assert.ok(mssqlSpec);
        assert.ok(mssqlSpec.sql.includes(`[__mj_BizAppsCollaboration].[${COLLABORATION_CHAT_SCOPE_FUNCTION_NAME}](@p0, @p1)`));
        assert.deepEqual(mssqlSpec.parameters, [CHAT_ID.toLowerCase(), USER_ID.toLowerCase()]);

        const pgSpec = buildStructuralChatScopeQuery('postgresql', CHAT_ID, USER_ID);
        assert.ok(pgSpec);
        assert.ok(pgSpec.sql.includes(`__mj_bizappscollaboration."${COLLABORATION_CHAT_SCOPE_FUNCTION_NAME}"($1::uuid, $2::uuid)`));
        assert.deepEqual(pgSpec.parameters, [CHAT_ID.toLowerCase(), USER_ID.toLowerCase()]);

        assert.equal(buildStructuralChatScopeQuery('mssql', "' OR '1'='1", USER_ID), null);
        assert.equal(buildStructuralChatScopeQuery('postgresql', CHAT_ID, 'not-a-uuid'), null);
    });

    it('invokes ExecuteSQL across mssql/postgresql, deduplicates multi-band pairs, and fails closed on invalid UUIDs', async () => {
        const badCalls: Array<{
            sql: string;
            params: StructuralChatScopeSqlParam[] | undefined;
            options: StructuralChatScopeExecuteOptions | undefined;
        }> = [];
        const badProvider = makeMockProvider('mssql', [{ SpaceID: SPACE_A, Band: 'Shared' }], badCalls);
        const failClosed = await resolveStructuralChatScope({
            provider: badProvider,
            primaryScopeRecordId: 'bad-id',
            userId: USER_ID,
        });
        assert.equal(badCalls.length, 0, 'Invalid UUID must not issue any SQL call');
        assert.deepEqual(failClosed.pairs, []);

        const mssqlCalls: Array<{
            sql: string;
            params: StructuralChatScopeSqlParam[] | undefined;
            options: StructuralChatScopeExecuteOptions | undefined;
        }> = [];
        const mssqlProvider = makeMockProvider(
            'mssql',
            [
                { SpaceID: SPACE_B.toUpperCase(), Band: 'Team' },
                { SpaceID: SPACE_A, Band: 'Shared' },
                { SpaceID: SPACE_B, Band: 'Shared' },
                { SpaceID: SPACE_B, Band: 'Team' },
            ],
            mssqlCalls,
        );
        const mssqlResolution = await resolveStructuralChatScope({
            provider: mssqlProvider,
            primaryScopeRecordId: CHAT_ID,
            userId: USER_ID,
        });
        assert.equal(mssqlCalls.length, 1);
        assert.equal(mssqlCalls[0]?.options?.readOnlyTransaction, true);
        assert.deepEqual(mssqlResolution.pairs, [
            { SpaceID: SPACE_A, Band: 'Shared' },
            { SpaceID: SPACE_B, Band: 'Shared' },
            { SpaceID: SPACE_B, Band: 'Team' },
        ]);
        assert.equal(hasStructuralChatScopeAccess(mssqlResolution, SPACE_A, 'Team'), false);
        assert.equal(hasStructuralChatScopeAccess(mssqlResolution, SPACE_B, 'Team'), true);

        const pgCalls: Array<{
            sql: string;
            params: StructuralChatScopeSqlParam[] | undefined;
            options: StructuralChatScopeExecuteOptions | undefined;
        }> = [];
        const pgProvider = makeMockProvider(
            'postgresql',
            [
                { spaceid: SPACE_A, band: 'Shared' },
                { spaceid: SPACE_A, band: 'Team' },
            ],
            pgCalls,
        );
        const pgResolution = await resolveStructuralChatScope({
            provider: pgProvider,
            primaryScopeRecordId: CHAT_ID,
            userId: USER_ID,
        });
        assert.equal(pgCalls.length, 1);
        assert.ok(pgCalls[0]?.sql.includes('__mj_bizappscollaboration."fnCollaborationChatScope"($1::uuid, $2::uuid)'));
        assert.deepEqual(pgResolution.pairs, [
            { SpaceID: SPACE_A, Band: 'Shared' },
            { SpaceID: SPACE_A, Band: 'Team' },
        ]);
    });

    it('enforces zero any, zero unknown, and zero BaseEntity.Get()/Set() across CS-1 TypeScript files', () => {
        const repoRoot = resolve(import.meta.dirname, '..', '..', '..');
        const tsFiles = [
            resolve(repoRoot, 'packages/Core/src/chat-scope.ts'),
            resolve(repoRoot, 'packages/Core/src/chat-scope.test.ts'),
            resolve(repoRoot, 'packages/CoreEntitiesServer/src/structural-chat-scope.ts'),
            resolve(repoRoot, 'packages/CoreEntitiesServer/src/structural-chat-scope.test.ts'),
        ];

        for (const filePath of tsFiles) {
            const content = readFileSync(filePath, 'utf8');
            const sourceFile = ts.createSourceFile(filePath, content, ts.ScriptTarget.Latest, true);
            const violations: string[] = [];

            const visit = (node: ts.Node): void => {
                if (node.kind === ts.SyntaxKind.AnyKeyword || node.kind === ts.SyntaxKind.UnknownKeyword) {
                    const { line } = sourceFile.getLineAndCharacterOfPosition(node.getStart(sourceFile));
                    violations.push(`line ${line + 1}: forbidden keyword ${ts.SyntaxKind[node.kind]}`);
                }
                if (
                    ts.isCallExpression(node) &&
                    ts.isPropertyAccessExpression(node.expression) &&
                    (node.expression.name.text === 'Get' || node.expression.name.text === 'Set')
                ) {
                    const { line } = sourceFile.getLineAndCharacterOfPosition(node.getStart(sourceFile));
                    violations.push(`line ${line + 1}: forbidden .${node.expression.name.text}() call`);
                }
                ts.forEachChild(node, visit);
            };

            visit(sourceFile);
            assert.deepEqual(violations, [], `${filePath} violations: ${violations.join(', ')}`);
        }
    });
});
